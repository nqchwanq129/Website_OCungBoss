const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
const utf8Fatal = new TextDecoder('utf-8', { fatal: true });

function validateTextBuffer(buf, label) {
  assert(buf.length > 0, `Empty text file is not expected: ${label}`);
  assert(
    !(buf.length >= 3 && buf[0] === 0xef && buf[1] === 0xbb && buf[2] === 0xbf),
    `UTF-8 BOM is not allowed: ${label}`,
  );
  assert(
    !(buf.length >= 2 && ((buf[0] === 0xff && buf[1] === 0xfe) || (buf[0] === 0xfe && buf[1] === 0xff))),
    `UTF-16 BOM is not allowed: ${label}`,
  );
  assert(!buf.includes(0x00), `NUL byte found in text file: ${label}`);
  assert(!buf.includes(0x0d), `CR (\\r) line ending is not allowed; expected LF only: ${label}`);
  assert.equal(buf[buf.length - 1], 0x0a, `Missing final newline (LF): ${label}`);
  let decoded;
  try {
    decoded = utf8Fatal.decode(buf);
  } catch (err) {
    assert.fail(`Invalid UTF-8 byte sequence in ${label}: ${err.message}`);
  }
  assert(!decoded.includes('\uFFFD'), `Replacement character U+FFFD found in ${label}`);
  return decoded;
}

// 1. Self-test validator against bad byte sequences in memory.
for (const [probe, regex] of [
  [Buffer.from([0xef, 0xbb, 0xbf, 0x61, 0x0a]), /UTF-8 BOM is not allowed/],
  [Buffer.from('hello\r\n', 'utf8'), /expected LF only/],
  [Buffer.from('hello', 'utf8'), /Missing final newline/],
  [Buffer.from([0xc3, 0x28, 0x0a]), /Invalid UTF-8 byte sequence/],
  [Buffer.from('lỗi \uFFFD ký tự\n', 'utf8'), /Replacement character U\+FFFD/],
]) {
  assert.throws(() => validateTextBuffer(probe, 'probe'), regex);
}

// 2. Verify .editorconfig and .gitattributes rules.
const editorconfig = validateTextBuffer(fs.readFileSync(path.join(root, '.editorconfig')), '.editorconfig');
for (const r of [
  /^root\s*=\s*true$/m,
  /^charset\s*=\s*utf-8$/m,
  /^end_of_line\s*=\s*lf$/m,
  /^insert_final_newline\s*=\s*true$/m,
])
  assert.match(editorconfig, r);

const gitattributes = validateTextBuffer(fs.readFileSync(path.join(root, '.gitattributes')), '.gitattributes');
for (const r of [/^\*\s+text=auto\s+eol=lf$/m, /^\*\.png\s+binary$/m, /^\*\.jpg\s+binary$/m])
  assert.match(gitattributes, r);

// 3. Verify Git attribute resolution via native `git check-attr`.
const textProbes = [
  'README.md',
  'AGENTS.md',
  '.gitignore',
  '.editorconfig',
  '.gitattributes',
  '.env.example',
  'apps/web/app/page.tsx',
  'docs/README.md',
  'tools/check-encoding.cjs',
  'playwright.config.ts',
  'e2e/smoke.spec.ts',
];
const binaryProbes = ['design/stitch/01-trang-chu.png', 'design/stitch/assets/hero-dog.jpg'];
const attrRes = spawnSync('git', ['check-attr', '--stdin', 'text', 'eol', 'binary'], {
  cwd: root,
  input: `${[...textProbes, ...binaryProbes].join('\n')}\n`,
  encoding: 'utf8',
});
if (attrRes.error) throw attrRes.error;
assert.equal(attrRes.status, 0, attrRes.stderr);

const attrMap = new Map();
for (const line of attrRes.stdout.split(/\r?\n/).filter(Boolean)) {
  const m = line.match(/^(.+?): (text|eol|binary): (.+)$/);
  assert(m, `Unexpected git check-attr output: ${line}`);
  if (!attrMap.has(m[1])) attrMap.set(m[1], {});
  attrMap.get(m[1])[m[2]] = m[3];
}
for (const f of textProbes) {
  assert.equal(attrMap.get(f)?.text, 'set', `Expected text=set for ${f}`);
  assert.equal(attrMap.get(f)?.eol, 'lf', `Expected eol=lf for ${f}`);
  assert.notEqual(attrMap.get(f)?.binary, 'set', `Text file marked binary: ${f}`);
}
for (const f of binaryProbes) {
  assert.equal(attrMap.get(f)?.binary, 'set', `Expected binary=set for ${f}`);
  assert.equal(attrMap.get(f)?.text, 'unset', `Expected text=unset for ${f}`);
}

// 4. Verify public text files and Vietnamese UTF-8 samples.
const filesToCheck = [
  'README.md',
  'AGENTS.md',
  '.gitignore',
  '.editorconfig',
  '.gitattributes',
  '.prettierignore',
  '.prettierrc.json',
  'package.json',
  'pnpm-workspace.yaml',
  'playwright.config.ts',
  'apps/web/lib/fixtures.ts',
  'apps/web/app/preview/FixturePlayground.tsx',
  'apps/web/app/preview/page.tsx',
  'apps/web/app/page.tsx',
  'apps/web/app/globals.css',
];
function collect(dirRel) {
  const absDir = path.join(root, dirRel);
  if (!fs.existsSync(absDir)) return;
  for (const e of fs.readdirSync(absDir, { withFileTypes: true })) {
    const rel = path.posix.join(dirRel, e.name);
    if (e.isDirectory()) collect(rel);
    else filesToCheck.push(rel);
  }
}
for (const dir of ['docs', 'tools', '.githooks', 'e2e']) collect(dir);

// Generated by Next.js and intentionally excluded from source checks because
// dev/build may rewrite it with platform line endings: apps/web/next-env.d.ts.

const vnSamples = new Map([
  ['AGENTS.md', ['Điểm vào AI', 'dữ liệu ảo', 'nghiệm thu']],
  ['docs/README.md', ['OCungBoss là website tiếng Việt cho người nuôi chó, mèo', 'chăm sóc thú cưng']],
  ['docs/core/RULES and WORKFLOW.md', ['Quy tắc viết code', 'tiếng Việt theo dự án']],
  [
    'docs/tasks/006-thong-nhat-encoding-va-line-endings.md',
    ['Thống nhất encoding và line endings', 'kết thúc dòng đúng cấu hình'],
  ],
]);
for (const relPath of filesToCheck) {
  const text = validateTextBuffer(fs.readFileSync(path.join(root, relPath)), relPath);
  const phrases = vnSamples.get(relPath);
  if (phrases) {
    assert.equal(text, text.normalize('NFC'), `Expected NFC Vietnamese text in ${relPath}`);
    for (const p of phrases) assert(text.includes(p), `Missing Vietnamese sample "${p}" in ${relPath}`);
  }
}

// 5. Verify PNG/JPG binary headers remain untouched.
const pngHdr = fs.readFileSync(path.join(root, 'design/stitch/01-trang-chu.png')).subarray(0, 8);
assert.deepEqual([...pngHdr], [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a], 'PNG header corrupted');
const assetsDir = path.join(root, 'design/stitch/assets');
const jpgFile = fs.readdirSync(assetsDir).find((n) => n.endsWith('.jpg'));
assert(jpgFile, 'Expected JPG asset in design/stitch/assets');
const jpgHdr = fs.readFileSync(path.join(assetsDir, jpgFile)).subarray(0, 3);
assert.deepEqual([...jpgHdr], [0xff, 0xd8, 0xff], 'JPEG SOI header corrupted');

console.log(
  `PASS: .editorconfig & .gitattributes verified; ${filesToCheck.length} public text files are UTF-8 LF with final newline; Vietnamese samples & PNG/JPG binary headers intact.`,
);
